export function getProduct(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function getRelatedProducts(product: CommerceProduct) {
  return products.filter((candidate) => candidate.category === product.category && candidate.id !== product.id).slice(0, 3);
}

export function isProductCategory(value: string): value is ProductCategory {
  return value === "Streaming" || value === "Produktivitas" || value === "Kreatif" || value === "Edukasi" || value === "Keamanan";
}
